/**
 * Filter case types matching query letter/word case-insensitively
 */
export function searchCaseTypes(query: string, maxResults = 12): string[] {
  if (!query || !query.trim()) {
    return DETAILED_CASE_TYPES.slice(0, maxResults);
  }
  const q = query.toLowerCase().trim();
  
  // Prioritize startsWith matching first, then includes matching
  const startsWithMatches: string[] = [];
  const includesMatches: string[] = [];

  for (const type of DETAILED_CASE_TYPES) {
    const lower = type.toLowerCase();
    if (lower.startsWith(q)) {
      startsWithMatches.push(type);
    } else if (lower.includes(q)) {
      includesMatches.push(type);
    }
  }

  return [...startsWithMatches, ...includesMatches].slice(0, maxResults);
}
